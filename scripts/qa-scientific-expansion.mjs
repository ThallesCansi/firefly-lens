// Uses an existing Playwright installation; start Next with the real Python API configured.
import assert from "node:assert/strict";
import { mkdir, readFile, writeFile } from "node:fs/promises";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const base = process.env.QA_BASE_URL || "http://localhost:3118";
const out = process.env.QA_OUTPUT || "docs/national-qa";
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ channel: "chrome", headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: "reduce" });
// External basemaps are unrelated to local scientific/data integration checks.
await context.route(/https:\/\/(basemaps\.cartocdn\.com|tiles\.openfreemap\.org)\/.*/, (route) => route.fulfill({ json: {
  version: 8, sources: {}, layers: [{ id: "background", type: "background", paint: { "background-color": "#24382e" } }],
} }));
await context.addInitScript(() => { localStorage.setItem("firefly-lens-intro-done", "1"); localStorage.setItem("firefly-lens-theme", "dark"); localStorage.setItem("firefly-lens-tour-auto-disabled-v1", "true"); });
const page = await context.newPage();
const errors = [], checks = [], requests = [];
const showTop = (locator) => locator.evaluate((el) => window.scrollTo({ top: Math.max(0, scrollY+el.getBoundingClientRect().top-96), behavior: "instant" }));
page.on("pageerror", (error) => errors.push(error.message));
page.on("request", (request) => { if (request.url().includes("/data/continental/")) requests.push(request.url()); });
try {
  const status = await context.request.get(`${base}/api/analytics/status`);
  assert.equal(status.status(), 200, await status.text());
  checks.push("Next proxy reaches configured Python health endpoint");
  await page.goto(base, { waitUntil: "networkidle" });
  const report = page.locator(".analytics-report").filter({ has: page.getByRole("heading", { name: "Understand the past. Assess the outlook." }) });
  async function choose(id) {
    await page.getByRole("button", { name: "Coordinates", exact: true }).click();
    await page.locator('[data-tour="presets"]').selectOption(id);
    await page.getByRole("button", { name: "Analyze area", exact: true }).click();
  }
  await choose("pantanal");
  await page.locator('[data-tour="analysis-status"][data-tour-ready="true"]').waitFor({ timeout: 60000 });
  assert.equal(await page.locator('.analysis-scroll').getByRole("heading", { name: "Historical Fire Activity", exact: true }).count(), 1);
  await report.locator('[data-tour="analytics-history"][data-tour-ready="true"]').waitFor({ timeout: 60000 });
  const area = await report.getAttribute("data-tour-area");
  const history = report.locator('[data-tour="analytics-history"]');
  assert.match(await history.locator(".analytics-card").first().innerText(), /2002-07.*2026-11/s);
  await report.getByLabel("Resolution").selectOption("annual");
  assert.equal(await history.getByRole("heading", { name: "Annual activity", exact: true }).count(), 1);
  await report.getByLabel("Resolution").selectOption("monthly");
  await report.getByLabel("Time span").selectOption("selection");
  assert.equal(await report.getAttribute("data-tour-area"), area);
  checks.push("Prominent full monthly record, annual switch and chart exploration preserve geometry");
  await showTop(history.locator(".analytics-card").first());
  await page.screenshot({ path: `${out}/history-dark.png` });
  await page.getByRole("button", { name: "Switch to light theme", exact: true }).click();
  await page.waitForFunction(() => document.documentElement.dataset.theme === "light");
  await showTop(history.locator(".analytics-card").first());
  await page.screenshot({ path: `${out}/history-light.png` });
  await page.getByRole("button", { name: "2D Map", exact: true }).click();
  await page.getByRole("button", { name: "3D Globe", exact: true }).click();
  assert.equal(await report.getAttribute("data-tour-area"), area);
  await page.getByRole("button", { name: "Switch to dark theme", exact: true }).click();
  checks.push("Light/dark and 2D/3D switches preserve the analysis geometry");
  await report.getByRole("tab", { name: "Forecast", exact: true }).click();
  await report.getByText("No current numeric forecast", { exact: true }).waitFor({ timeout: 60000 });
  assert.match(await report.locator('[data-tour="analytics-forecast"]').innerText(), /orbital drift/);
  await report.getByRole("button", { name:"Run retrospective forecast",exact:true }).click();
  await report.getByRole("heading", { name:"Past forecast and later eligible observations",exact:true }).waitFor({ timeout:60000 });
  assert.match(await report.innerText(),/past forecast experiment/);
  await showTop(report.getByRole("heading", { name:"What would the model have forecast?",exact:true }).locator(".."));
  await page.screenshot({ path:`${out}/retrospective-forecast.png` });
  await report.getByText("NASA GFWED / GEOS-5 · experimental forecast", { exact:true }).waitFor({ timeout:60000 });
  assert.match(await report.innerText(),/local-noon field/);
  await showTop(report.getByRole("heading", { name:"Fire Danger Assessment",exact:true }).locator(".."));
  await page.screenshot({ path:`${out}/official-fwi.png` });
  checks.push("Current activity predictions remain gated; actual retrospective forecasts and official numeric NASA FWI are distinct");
  await choose("raw:PRY");
  const raw = page.locator('.analysis-report .analytics-report').first();
  await raw.getByRole("heading", { name: /National fire activity · Paraguay/ }).waitFor();
  const manifest = await (await context.request.get(`${base}/data/continental/paraguay/national.json`)).json();
  const september = manifest.sections.history.data.monthly.find((r) => r.date === "2025-09");
  await raw.getByRole("heading",{ name:"Historical fire activity, over time",exact:true }).waitFor();
  assert.match(await raw.innerText(), new RegExp(september.value.toLocaleString("en",{ maximumFractionDigits:2 })));
  assert.equal(await raw.getByText(/entire country only/).count() > 0, true);
  const month = page.locator('.analysis-scroll').getByLabel("Map month");
  await month.selectOption("2022-09");
  await page.waitForFunction(() => document.querySelector('.map-key')?.textContent?.includes("Loading") !== true);
  assert.equal(requests.filter((url) => url.includes("/map/")).every((url) => /\/(2025-09|2022-09)\//.test(url)), true);
  checks.push("Paraguay national harmonization uses its own country report while the map loads selected-month raw tiles");
  await showTop(raw.locator(".analytics-card").first());
  await page.screenshot({ path: `${out}/paraguay-dark.png` });
  const downloadReady = page.waitForEvent("download");
  await page.getByRole("button", { name:"CSV",exact:true }).click();
  const download = await downloadReady;
  const csv = (await readFile(await download.path(),"utf8")).trim().split("\n");
  assert.equal(csv[0],"period,cell_id,longitude,latitude,modis_aqua_raw,viirs_noaa20_raw");
  const ownRaw = await (await context.request.get(`${base}/data/continental/paraguay/manifest.json`)).json();
  const ownMonth = ownRaw.monthly.find((r) => r.date === "2022-09");
  const values = csv.slice(1).map((line) => line.split(","));
  assert.equal(values.every((row) => row[0] === "2022-09"),true);
  assert.equal(values.reduce((sum,row) => sum+Number(row[4]),0),ownMonth.modis);
  assert.equal(values.reduce((sum,row) => sum+Number(row[5]),0),ownMonth.viirs);
  await page.getByRole("button", { name:"Share",exact:true }).click();
  assert.equal(new URL(page.url()).searchParams.get("area"),"country:PRY");
  const sharedPage = await context.newPage();
  await sharedPage.goto(page.url());
  await sharedPage.locator(".analysis-report").getByRole("heading",{ name:"National fire activity · Paraguay",exact:true }).waitFor();
  assert.equal(await sharedPage.locator(".analysis-scroll").getByLabel("Map month").inputValue(),"2022-09");
  await sharedPage.close();
  checks.push("Country share links restore the exact country/month and CSV totals reconcile with that country's raw archive");
  await page.setViewportSize({ width: 320, height: 900 });
  await showTop(raw.locator(".analytics-card").first());
  await page.screenshot({ path: `${out}/paraguay-mobile-320.png` });
  const overflow = await page.evaluate(() => ({ width: innerWidth, scroll: document.documentElement.scrollWidth,
    elements: [...document.querySelectorAll("body *")].filter((el) => el.getBoundingClientRect().right > innerWidth+1 && getComputedStyle(el).position !== "absolute")
      .slice(0,12).map((el) => ({ tag: el.tagName, class: el.className, width: el.getBoundingClientRect().width, text: el.textContent.slice(0,70) })) }));
  if (overflow.scroll > overflow.width+1) console.log(JSON.stringify(overflow));
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth+1), true, "Mobile document overflow");
  await page.screenshot({ path: `${out}/paraguay-mobile-320.png` });
  checks.push("320px mobile page has no document-level horizontal overflow");
  await page.setViewportSize({ width:1440,height:1000 });
  await choose("raw:ECU");
  await page.locator('.analysis-report').getByRole("heading",{ name:/National fire activity · Ecuador/ }).waitFor();
  checks.push("Changing countries loads Ecuador’s own evaluated harmonization without borrowing Paraguay results");
  await page.goto(`${base}/method#fire-danger-risk`);
  await page.getByRole("heading", { name: "What the Canadian FWI System measures", exact: true }).waitFor();
  assert.equal(await page.getByRole("tab", { name: "Fire Danger & Risk", exact: true }).getAttribute("aria-selected"), "true");
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth+1), true);
  await page.screenshot({ path: `${out}/methods-mobile.png` });
  checks.push("Deep-linked Fire Danger & Risk methods and equations work on mobile");
  assert.deepEqual(errors, []);
  await writeFile(`${out}/browser-results.json`, JSON.stringify({ checks, errors, raw_tile_requests: requests.filter((url) => url.includes("/map/")).length }, null, 2));
  console.log(JSON.stringify({ checks, errors }, null, 2));
} finally { await browser.close(); }
